// returns translated item name or null
AH.trItemName = function (s, L) {
  if (typeof AH.PREFIX === 'undefined') return null;
  for (const sn in AH.SET_TR) if (s.startsWith(sn + ' ')) {
    const rest = s.slice(sn.length + 1); if (!AH.FR_NOUN[rest]) continue;
    return L === 'fr' ? AH.FR_NOUN[rest][0] + ' ' + AH.SET_TR[sn].fr : AH.SET_TR[sn].hu + ' ' + AH.I18N.hu[rest];
  }
  const P = itemParts();
  const w = s.split(' ');
  if (w.length === 2 && P.ra[w[0]] && P.rb[w[1]]) return L === 'fr' ? AH.RB_FR[w[1]] + ' ' + AH.RA_FR[w[0]] : AH.RA_HU[w[0]] + AH.RB_HU[w[1]];
  // find base name
  let base = null, at = -1;
  for (const b of P.bases) { const i = (' ' + s + ' ').indexOf(' ' + b + ' '); if (i >= 0) { base = b; at = i; break; } }
  if (!base) return null;
  const before = s.slice(0, at).trim(), after = s.slice(at + base.length).trim();
  let rar = null, mat = null, pre = null, suf = null;
  let bw = before ? before.split(' ') : [];
  if (bw.length && P.rar[bw[0]]) rar = bw.shift();
  if (bw.length && P.mats[bw[bw.length - 1]]) mat = bw.pop();
  if (bw.length) { pre = P.pre[bw.join(' ')]; if (!pre) return null; }
  if (after) { suf = P.suf[after]; if (!suf) return null; }
  if (L === 'fr') {
    const [n, g] = AH.FR_NOUN[base];
    const out = [n];
    if (mat) out.push(AH.MAT_FR[mat]);
    if (pre) out.push(frAdj(AH.PRE_FR[pre], g));
    if (suf) out.push(AH.SUF_FR[suf]);
    if (rar) out.push(frAdj(AH.RAR_FR[rar], g));
    return out.join(' ');
  }
  const out = [];
  if (rar) out.push(AH.RAR_HU[rar]);
  if (pre && suf) out.push(AH.PRE_HU[pre] + ',', AH.SUF_HU[suf]);
  else if (pre) out.push(AH.PRE_HU[pre]);
  else if (suf) out.push(AH.SUF_HU[suf]);
  if (mat) out.push(AH.I18N.hu[mat]);
  out.push(AH.I18N.hu[base]);
  return out.join(' ');
};
